"""Generate ccwin/os/core/font.lua from the CC:Tweaked terminal font atlas.

Atlas layout (verified empirically):
  - 256x256, 1 bit per pixel, 16x16 grid of glyphs
  - each glyph cell is 8x11 texels, glyph code = row*16 + col
  - the glyph itself sits at cell columns 1..6 and rows 1..8
    (cols 0/7 and rows 0/9/10 are bearings and are never used by any glyph)
  -> cropping cols 1..6 / rows 1..9 gives exactly the 6x9 pixels that
     ComputerCraft draws for one character cell.
"""
import struct, zlib

SRC = r"C:\Users\User\Desktop\cc ce\term_font.png"
OUT = r"C:\Users\User\Desktop\cc ce\ccwin\os\core\font.lua"

data = open(SRC, "rb").read()
pos, idat = 8, b""
while pos < len(data):
    ln = struct.unpack(">I", data[pos:pos + 4])[0]
    typ = data[pos + 4:pos + 8]
    if typ == b"IDAT":
        idat += data[pos + 8:pos + 8 + ln]
    pos += 12 + ln

raw = zlib.decompress(idat)
w = h = 256
stride = 32
rows, prev, i = [], bytearray(stride), 0
for y in range(h):
    f = raw[i]; i += 1
    line = bytearray(raw[i:i + stride]); i += stride
    if f == 1:
        for x in range(1, stride):
            line[x] = (line[x] + line[x - 1]) & 0xFF
    elif f == 2:
        for x in range(stride):
            line[x] = (line[x] + prev[x]) & 0xFF
    elif f == 3:
        for x in range(stride):
            a = line[x - 1] if x else 0
            line[x] = (line[x] + ((a + prev[x]) >> 1)) & 0xFF
    elif f == 4:
        for x in range(stride):
            a = line[x - 1] if x else 0
            b = prev[x]
            c = prev[x - 1] if x else 0
            p = a + b - c
            pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
            pr = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
            line[x] = (line[x] + pr) & 0xFF
    rows.append(line)
    prev = line


def texel(x, y):
    return (rows[y][x >> 3] >> (7 - (x & 7))) & 1


glyphs = []
for ch in range(256):
    cx, cy = ch % 16, ch // 16
    ox, oy = cx * 8, cy * 11
    out = []
    for r in range(9):          # cell rows 1..9
        byte = 0
        for c in range(6):      # cell cols 1..6
            if texel(ox + 1 + c, oy + 1 + r):
                byte |= (1 << c)
        out.append(byte)
    glyphs.append(out)

lines = []
lines.append("-- Auto-generated by tools/gen_font.py - do not edit by hand.")
lines.append("-- Glyph bitmap font cropped from CC:Tweaked's term_font.png atlas.")
lines.append("-- Every glyph is 6 pixels wide and 9 pixels tall (one character cell).")
lines.append("-- Bit `2^x` of row `y` is the pixel at (x, y); the top-left pixel is (0, 0).")
lines.append("local WIDTH, HEIGHT = 6, 9")
lines.append("local CHUNKS = {")
for ch in range(256):
    body = "".join("\\%03d" % b for b in glyphs[ch])
    label = repr(chr(ch)) if 32 <= ch < 127 else ""
    lines.append('    "%s", -- %d %s' % (body, ch, label))
lines.append("}")
lines.append("local DATA = table.concat(CHUNKS)")
lines.append("")
lines.append("local glyphs = {}")
lines.append("for code = 0, 255 do")
lines.append("    glyphs[code] = DATA:sub(code * 9 + 1, code * 9 + 9)")
lines.append("end")
lines.append("")
lines.append("return { width = WIDTH, height = HEIGHT, glyphs = glyphs }")
lines.append("")

import os
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", OUT, sum(len(g) for g in glyphs), "glyph bytes")
